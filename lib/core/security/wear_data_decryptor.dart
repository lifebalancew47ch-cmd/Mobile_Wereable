/// Desencriptador AES-256 CBC para los lotes de sensores recibidos desde la capa
/// nativa de Android (prevención de fugas de datos de salud en SharedPreferences).
abstract final class WearDataDecryptor {
  static const String prefix = 'enc:';
  static const String _wearPayloadSalt = 'LifeBalance_WearOS_Secure_Seed_2026';

  static Uint8List get _keyBytes {
    final sha256Bytes = sha256.convert(utf8.encode(_wearPayloadSalt)).bytes;
    return Uint8List.fromList(sha256Bytes);
  }

  static Uint8List get _ivBytes {
    final sha256Bytes = sha256.convert(utf8.encode('${_wearPayloadSalt}_IV')).bytes;
    return Uint8List.fromList(sha256Bytes.sublist(0, 16));
  }

  /// Desencripta la cadena [rawInput] si comienza con el prefijo `enc:`.
  /// Si no está encriptada (p. ej. datos legacy), la retorna tal cual.
  static String decrypt(String rawInput) {
    if (!rawInput.startsWith(prefix)) {
      return rawInput;
    }

    try {
      final base64Payload = rawInput.substring(prefix.length);
      final cipherBytes = base64.decode(base64Payload);
      final decryptedBytes = _aes256CbcDecrypt(cipherBytes, _keyBytes, _ivBytes);
      return utf8.decode(decryptedBytes);
    } catch (e) {
      AppLog.d('[WearDataDecryptor] Error desencriptando payload: $e');
      return rawInput;
    }
  }

  // --- Implementación pura Dart de AES-256 CBC Decryption ---

  static Uint8List _aes256CbcDecrypt(
    Uint8List cipherText,
    Uint8List key,
    Uint8List iv,
  ) {
    if (cipherText.length % 16 != 0) {
      throw ArgumentError('Invalid ciphertext length');
    }

    final keyWords = _expandKey(key);
    final decrypted = Uint8List(cipherText.length);
    Uint8List previousBlock = iv;

    for (int offset = 0; offset < cipherText.length; offset += 16) {
      final block = cipherText.sublist(offset, offset + 16);
      final decryptedBlock = _decryptBlock(block, keyWords);

      for (int i = 0; i < 16; i++) {
        decrypted[offset + i] = decryptedBlock[i] ^ previousBlock[i];
      }
      previousBlock = block;
    }

    return _unpadPkcs7(decrypted);
  }

  static Uint8List _unpadPkcs7(Uint8List data) {
    if (data.isEmpty) return data;
    final paddingLen = data.last;
    if (paddingLen < 1 || paddingLen > 16 || paddingLen > data.length) {
      return data;
    }
    for (int i = data.length - paddingLen; i < data.length; i++) {
      if (data[i] != paddingLen) return data;
    }
    return data.sublist(0, data.length - paddingLen);
  }

