  static Uint8List _decryptBlock(Uint8List block, List<Uint32List> roundKeys) {
    var state = List<int>.filled(16, 0);
    for (int i = 0; i < 16; i++) {
      state[i] = block[i];
    }

    // Initial AddRoundKey
    _addRoundKey(state, roundKeys[14]);

    for (int r = 13; r >= 1; r--) {
      _invShiftRows(state);
      _invSubBytes(state);
      _addRoundKey(state, roundKeys[r]);
      _invMixColumns(state);
    }

    _invShiftRows(state);
    _invSubBytes(state);
    _addRoundKey(state, roundKeys[0]);

    return Uint8List.fromList(state);
  }

  static void _addRoundKey(List<int> state, Uint32List rk) {
    for (int c = 0; c < 4; c++) {
      final w = rk[c];
      state[c * 4] ^= (w >> 24) & 0xFF;
      state[c * 4 + 1] ^= (w >> 16) & 0xFF;
      state[c * 4 + 2] ^= (w >> 8) & 0xFF;
      state[c * 4 + 3] ^= w & 0xFF;
    }
  }

  static void _invSubBytes(List<int> state) {
    for (int i = 0; i < 16; i++) {
      state[i] = _sBoxInv[state[i]];
    }
  }

  static void _invShiftRows(List<int> state) {
    // Row 1: right shift 1
    int temp = state[13];
    state[13] = state[9];
    state[9] = state[5];
    state[5] = state[1];
    state[1] = temp;

    // Row 2: right shift 2
    temp = state[2];
    state[2] = state[10];
    state[10] = temp;
    temp = state[6];
    state[6] = state[14];
    state[14] = temp;

    // Row 3: right shift 3
    temp = state[3];
    state[3] = state[7];
    state[7] = state[11];
    state[11] = state[15];
    state[15] = temp;
  }

  static int _mul(int a, int b) {
    int p = 0;
    for (int counter = 0; counter < 8; counter++) {
      if ((b & 1) != 0) p ^= a;
      final hiBitSet = (a & 0x80) != 0;
      a = (a << 1) & 0xFF;
      if (hiBitSet) a ^= 0x1b;
      b >>= 1;
    }
    return p;
  }

  static void _invMixColumns(List<int> state) {
    for (int c = 0; c < 4; c++) {
      final idx = c * 4;
      final s0 = state[idx];
      final s1 = state[idx + 1];
      final s2 = state[idx + 2];
      final s3 = state[idx + 3];

      state[idx] = _mul(s0, 0x0e) ^ _mul(s1, 0x0b) ^ _mul(s2, 0x0d) ^ _mul(s3, 0x09);
      state[idx + 1] = _mul(s0, 0x09) ^ _mul(s1, 0x0e) ^ _mul(s2, 0x0b) ^ _mul(s3, 0x0d);
      state[idx + 2] = _mul(s0, 0x0d) ^ _mul(s1, 0x09) ^ _mul(s2, 0x0e) ^ _mul(s3, 0x0b);
      state[idx + 3] = _mul(s0, 0x0b) ^ _mul(s2, 0x0d) ^ _mul(s2, 0x09) ^ _mul(s3, 0x0e);
    }
  }
